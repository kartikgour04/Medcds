const mongoose = require('mongoose');
const { v4: uuidv4 } = require('uuid');

const reportSchema = new mongoose.Schema({
  reportId: { 
    type: String, 
    unique: true, 
    default: () => `RPT-${uuidv4().toUpperCase().slice(0, 8)}` 
  },
  assessmentId: { 
    type: mongoose.Schema.Types.ObjectId, 
    ref: 'Assessment', 
    required: true 
  },
  userId: { 
    type: mongoose.Schema.Types.ObjectId, 
    ref: 'User', 
    required: true 
  },
  
  // Report content snapshot
  patientName: String,
  patientAge: Number,
  patientGender: String,
  reportDate: { type: Date, default: Date.now },
  
  summary: {
    chiefComplaint: String,
    topDiagnosis: String,
    diagnosisConfidence: Number,
    drugsRecommended: Number,
    drugsAvoided: Number,
    warningCount: Number,
    overallRiskLevel: { type: String, enum: ['low', 'moderate', 'high', 'critical'] },
  },
  
  pdfPath: { type: String },
  pdfUrl: { type: String },
  pdfSize: { type: Number },
  
  isShared: { type: Boolean, default: false },
  shareToken: { type: String },
  shareExpiresAt: { type: Date },
  
  viewCount: { type: Number, default: 0 },
  downloadCount: { type: Number, default: 0 },
  
  disclaimer: {
    type: String,
    default: 'This report is generated by an AI-assisted Clinical Decision Support System and is NOT a prescription. It is intended to support, not replace, professional medical judgment. Always consult a qualified healthcare provider before making any medical decisions. The recommendations are based on population-level clinical guidelines and may not account for individual patient factors not captured in this assessment.'
  },
  
}, { timestamps: true });

module.exports = mongoose.model('Report', reportSchema);
